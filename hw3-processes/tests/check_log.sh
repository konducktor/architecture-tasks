#!/bin/sh
# Проверка инвариантов по логу: противоположные ворота не открыты одновременно,
# уровень воды не меняется при открытых воротах, вместимость камеры не превышена
awk '
function bad(message) { print "ЛОГ: " message ": " $0; errors++ }
{ sub(/^\[t= *[0-9]+\] /, "") }
$1 == "камера" && $3 == "открыты" {
    chamber = $2 + 0; side = ($NF == "(нижние)")
    if (op[chamber, 1 - side]) bad("противоположные ворота открыты одновременно")
    op[chamber, side] = 1
}
$1 == "камера" && $3 == "ворота" && $NF == "закрыты" { op[$2 + 0, ($(NF - 1) == "(нижние)")] = 0 }
$1 == "камера" && $3 == "уровень" && $5 == "изменён" {
    if (op[$2 + 0, 0] || op[$2 + 0, 1]) bad("уровень воды меняется при открытых воротах")
}
$1 == "судно" && /вошло в камеру/ { split($NF, load, "/"); if (load[1] + 0 > load[2] + 0) bad("вместимость превышена") }
/НАРУШЕНИЕ ИНВАРИАНТА/ { bad("нарушение, найденное самой программой") }
END { exit errors > 0 }
' "$1"
