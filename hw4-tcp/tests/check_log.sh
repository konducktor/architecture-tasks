#!/bin/sh
# Проверка инвариантов по логу сервера: противоположные ворота не открыты одновременно,
# уровень воды не меняется при открытых воротах, вместимость камеры не превышена.
# Учитываются только сообщения, которые сервер получил от ворот и камер (строки «<-»).
awk '
function bad(message) { print "ЛОГ: " message ": " $0; errors++ }
{ sub(/^\[t= *[0-9]+\] /, "") }
$1 == "<-" && $2 == "ворота" {
    chamber = $3 + 0; side = ($4 == "(нижние):")
    if ($5 == "открыты") {
        if (open_gate[chamber, 1 - side]) bad("противоположные ворота открыты одновременно")
        open_gate[chamber, side] = 1
    }
    if ($5 == "закрыты") open_gate[chamber, side] = 0
}
$1 == "<-" && $2 == "камера" && /уровень воды изменён/ {
    chamber = $3 + 0
    if (open_gate[chamber, 0] || open_gate[chamber, 1]) bad("уровень воды меняется при открытых воротах")
}
match($0, /занято [0-9]+\/[0-9]+/) {
    split(substr($0, RSTART + 7, RLENGTH - 7), load, "/")
    if (load[1] + 0 > load[2] + 0) bad("вместимость превышена")
}
/НАРУШЕНИЕ ИНВАРИАНТА/ { bad("нарушение, найденное самой программой") }
END { exit errors > 0 }
' "$1"
